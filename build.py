"""
Static site builder for Japanese Grammar Study.
Processes prompts, pre-compute furigana for lessons, and bundles dist/.
"""

import json
import re
import shutil
import tomllib
from pathlib import Path

import pykakasi

ROOT_DIR = Path(__file__).resolve().parent
DATA_DIR = ROOT_DIR / "data"
SRC_DIR = ROOT_DIR / "src"
DIST_DIR = ROOT_DIR / "dist"

# Initialize Kakasi
kks = pykakasi.kakasi()

# Regex to match kanji characters
KANJI_REGEX = re.compile(r"[\u4e00-\u9faf々]")

# Matches Markdown constructs that should NOT have furigana added:
# - Fenced code blocks (```...```)
# - Inline code (`...`)
# - Markdown links [text](url) -> extracts URL so it isn't touched
# - Existing HTML tags (<...>)
MARKDOWN_PROTECT_REGEX = re.compile(
    r"(```[\s\S]*?```|`[^`]+`|<[^>]+>|\[[^\]]+\]\([^)]+\))"
)


def _common_prefix_len(s1: str, s2: str) -> int:
    """Returns the number of identical leading characters in two strings."""
    for i, (c1, c2) in enumerate(zip(s1, s2)):
        if c1 != c2:
            return i
    return min(len(s1), len(s2))


def _split_okurigana(orig: str, hira: str) -> tuple[str, str, str, str]:
    """Splits matching leading/trailing kana away from the kanji/reading core."""
    # 1. Match leading kana (e.g., お in お茶)
    pre_len = _common_prefix_len(orig, hira)
    pre = orig[:pre_len]
    orig_rest = orig[pre_len:]
    hira_rest = hira[pre_len:]

    # 2. Match trailing kana on the remaining text (e.g., べる in 食べる)
    suf_len = _common_prefix_len(orig_rest[::-1], hira_rest[::-1])

    kanji = orig_rest[: len(orig_rest) - suf_len]
    post = orig_rest[len(orig_rest) - suf_len :]
    reading = hira_rest[: len(hira_rest) - suf_len]

    return pre, kanji, reading, post


def _token_to_ruby(orig: str, hira: str) -> str:
    """Formats a single token into HTML ruby tags, stripping matching okurigana."""
    if not KANJI_REGEX.search(orig) or orig == hira:
        return orig

    pre, kanji, reading, post = _split_okurigana(orig, hira)
    return f"{pre}<ruby>{kanji}<rt>{reading}</rt></ruby>{post}"


def add_furigana_plain(text: str) -> str:
    """Converts a segment of plain Japanese text to include ruby tags."""
    tokens = kks.convert(text)
    return "".join(_token_to_ruby(t["orig"], t["hira"]) for t in tokens)


def add_furigana(text: str) -> str:
    """Adds furigana while safely preserving Markdown code, links, and HTML."""
    parts = MARKDOWN_PROTECT_REGEX.split(text)
    result = []

    for part in parts:
        if not part:
            continue
        # If this part matched a protected Markdown pattern:
        if MARKDOWN_PROTECT_REGEX.fullmatch(part):
            # If it's a markdown link [anchor](url), convert furigana inside the anchor only
            link_match = re.match(r"\[([^\]]+)\]\(([^)]+)\)", part)
            if link_match:
                anchor, url = link_match.groups()
                result.append(f"[{add_furigana_plain(anchor)}]({url})")
            else:
                result.append(part)
        else:
            result.append(add_furigana_plain(part))

    return "".join(result)


def transform_tree(node: object, transform_fn) -> object:
    """Recursively transforms string values inside nested dicts/lists."""
    if isinstance(node, dict):
        return {k: transform_tree(v, transform_fn) for k, v in node.items()}
    if isinstance(node, list):
        return [transform_tree(item, transform_fn) for item in node]
    if isinstance(node, str):
        return transform_fn(node)
    return node


def process_lessons(raw_lessons: dict) -> dict:
    """Generates a keyed structure containing 'normal' and 'furigana' variants."""
    output = {}
    for lesson_id, content in raw_lessons.items():
        output[lesson_id] = {
            "normal": content,  # Original text is already clean
            "furigana": transform_tree(content, add_furigana),
        }
    return output


def build_prompts(prompts_path: Path, dest_path: Path) -> None:
    """Converts system_prompts.toml into a browser-readable JS global."""
    with open(prompts_path, "rb") as f:
        prompts = tomllib.load(f)

    js_content = "// Generated by build.py - Do not edit manually\n"
    js_content += (
        f"window.SYSTEM_PROMPTS = Object.freeze({json.dumps(prompts, indent=2)});\n"
    )
    dest_path.write_text(js_content, encoding="utf-8")


def main() -> None:
    """Build pipeline entry point."""
    if DIST_DIR.exists():
        shutil.rmtree(DIST_DIR)
    DIST_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Copy Frontend Assets
    shutil.copy2(SRC_DIR / "index.html", DIST_DIR / "index.html")
    shutil.copy2(SRC_DIR / "style.css", DIST_DIR / "style.css")
    shutil.copy2(SRC_DIR / "app.js", DIST_DIR / "app.js")

    # 2. Compile System Prompts TOML -> JS
    build_prompts(DATA_DIR / "system_prompts.toml", DIST_DIR / "prompts.js")

    # 3. Process Lessons JSON -> Normal + Furigana dist/lessons.json
    with open(DATA_DIR / "lessons.json", "r", encoding="utf-8") as f:
        raw_lessons = json.load(f)

    processed_lessons = process_lessons(raw_lessons)
    with open(DIST_DIR / "lessons.json", "w", encoding="utf-8") as f:
        json.dump(processed_lessons, f, ensure_ascii=False, indent=2)

    print("Build successful: dist/ generated.")


if __name__ == "__main__":
    main()
